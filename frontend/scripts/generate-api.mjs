/**
 * Regenerate the versioned backend schema, its TypeScript types and the stage field
 * metadata without a running server.
 */
import { spawnSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { format, resolveConfig } from "prettier";
import openapiTS, { astToString } from "openapi-typescript";

const result = spawnSync(
  "uv",
  [
    "run",
    "--project",
    "../backend",
    "python",
    "-c",
    [
      "import json",
      "from brainstorm_agent.api.main import create_app",
      "from brainstorm_agent.core.stage_contracts import STAGE_MODELS",
      "from brainstorm_agent.settings import Settings",
      "app = create_app(Settings(database_url='sqlite:///:memory:', llm_mode='fake', auto_create_schema=False, run_db_migrations_on_startup=False, redis_url='redis://localhost:6399/0'))",
      // Field order follows the stage contract (`sort_keys` would sort it alphabetically).
      "fields = {stage.value: list(model.model_json_schema()['properties'].items()) for stage, model in STAGE_MODELS.items()}",
      "print(json.dumps({'openapi': app.openapi(), 'fields': fields}))",
    ].join("; "),
  ],
  { encoding: "utf8" },
);
if (result.status !== 0) throw new Error(result.stderr);
const { openapi, fields } = JSON.parse(result.stdout);

/** Sort object keys recursively, like `json.dumps(sort_keys=True)`. */
function sortKeys(value) {
  if (Array.isArray(value)) return value.map(sortKeys);
  if (value && typeof value === "object") {
    return Object.fromEntries(
      Object.keys(value)
        .sort()
        .map((key) => [key, sortKeys(value[key])]),
    );
  }
  return value;
}

/** Editing kind of a stage field, from its JSON schema. */
function fieldKind(schema) {
  const variants = (schema.anyOf ?? [schema]).filter((variant) => variant.type !== "null");
  const [variant] = variants;
  if (variants.length !== 1) return "structured";
  if (variant.type === "string") return "text";
  if (variant.type === "boolean") return "boolean";
  if (variant.type === "array" && variant.items?.type === "string") return "list";
  return "structured";
}

const ACRONYMS = new Set(["api", "kpi", "mvp", "nfr", "ux"]);

/** Short UI label from the field name (`mvp_scope` -> "MVP scope"); descriptions are prompt text. */
function fieldLabel(name) {
  const words = name
    .split("_")
    .map((word) => (ACRONYMS.has(word) || word.length === 1 ? word.toUpperCase() : word));
  return [words[0].charAt(0).toUpperCase() + words[0].slice(1), ...words.slice(1)].join(" ");
}

const stageFields = Object.fromEntries(
  Object.entries(fields).map(([stage, properties]) => [
    stage,
    properties.map(([name, schema]) => ({
      name,
      label: fieldLabel(name),
      required: schema.gate_required === true,
      kind: fieldKind(schema),
    })),
  ]),
);

const schema = sortKeys(openapi);
const prettier = {
  ...(await resolveConfig("src/lib/backend/generated/api.ts")),
  parser: "typescript",
};
writeFileSync("src/lib/backend/generated/openapi.json", JSON.stringify(schema, null, 2) + "\n");
writeFileSync(
  "src/lib/backend/generated/api.ts",
  await format(astToString(await openapiTS(schema)), prettier),
);
writeFileSync(
  "src/lib/backend/generated/stage-fields.ts",
  await format(
    [
      "// Generated by scripts/generate-api.mjs from the backend stage contracts. Do not edit.",
      'import type { components } from "./api";',
      "",
      'export type StageFieldKind = "text" | "list" | "boolean" | "structured";',
      "",
      "export interface StageFieldSpec {",
      "  name: string;",
      "  label: string;",
      "  /** Required by the deterministic stage gate. */",
      "  required: boolean;",
      "  kind: StageFieldKind;",
      "}",
      "",
      `export const STAGE_FIELDS = ${JSON.stringify(stageFields)} as const satisfies Record<components["schemas"]["Stage"], readonly StageFieldSpec[]>;`,
      "",
    ].join("\n"),
    prettier,
  ),
);
